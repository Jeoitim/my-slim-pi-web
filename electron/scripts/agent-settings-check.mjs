import { _electron as electron } from "playwright";
import { randomUUID } from "node:crypto";
import { mkdir, readFile, writeFile, access } from "node:fs/promises";
import { resolve, join } from "node:path";
import { createJiti } from "jiti";
import assert from "node:assert/strict";

const area = resolve(`.local/agent-settings-${randomUUID()}`);
const agent = join(area, "agent 中文");
for (const directory of ["agents", "sessions", "install", "extensions/timrt-suite", "extensions/pi-permission-suite", "npm/node_modules/pi-subagents/agents"]) await mkdir(join(agent, directory), { recursive: true });
await writeFile(join(agent, "install/current-version"), "1.4.0");
await writeFile(join(agent, "extensions/timrt-suite/permissions.ts"), "export default function() {}\n");
await writeFile(join(agent, "extensions/timrt-suite/timrt-fast.mjs"), '// "approval-fallback" fixture\n');
const permissionFile = join(agent, "extensions/pi-permission-suite/config.json");
await writeFile(permissionFile, JSON.stringify({ reviewer: { humanFallback: "ask", keep: true } }));
const profileFile = join(agent, "agents/approver.md");
const prompt = "Native reviewer details stay inside Settings.\n审批模型说明与系统提示词。\n";
await writeFile(profileFile, `---\nname: approver\ndescription: Permission reviewer\ntools: []\nallowedAgents: none\n---\n${prompt}`);
await writeFile(join(agent, "npm/node_modules/pi-subagents/agents/cli-builtin.md"), "---\nname: cli-builtin\ndescription: Native CLI profile\n---\nRead-only builtin prompt.\n");
const hermesFile = join(agent, "hermes-memory-config.json");
await writeFile(hermesFile, JSON.stringify({ memoryMode: "policy-only", llmThinkingOverride: "off" }));
const model = (id, name) => ({ id, name, reasoning: true, input: ["text"], contextWindow: 32000, maxTokens: 512, cost: { input: 0, output: 0, cacheRead: 0, cacheWrite: 0 } });
await writeFile(join(agent, "models.json"), JSON.stringify({ providers: { fixture: { baseUrl: "http://127.0.0.1:1/v1", api: "openai-completions", apiKey: "test-only", models: [model("reviewer", "Review model"), model("memory", "Summary model")] } } }));
const environment = { ...process.env, PI_CODING_AGENT_DIR: agent, PI_DESKTOP_TEST_USER_DATA: join(area, "profile"), PI_OFFLINE: "1" };
for (const name of ["PI_WEB_PASSWORD", "PI_WEB_REMOTE", "ELECTRON_RUN_AS_NODE"]) delete environment[name];
const app = await electron.launch({ executablePath: process.env.PI_DESKTOP_E2E_EXECUTABLE || resolve("dist-desktop/win-unpacked/MySlimPiWeb.exe"), env: environment, args: [], timeout: 120_000 });
const { parseFrontmatter } = await createJiti(import.meta.url).import("../../lib/frontmatter.ts");
let origin;
try {
  const page = await app.firstWindow();
  page.setDefaultTimeout(45_000);
  const writes = [], errors = [];
  page.on("request", request => { if (request.method() === "POST" && new URL(request.url()).pathname.startsWith("/api/agent/")) writes.push(request.url()); });
  page.on("pageerror", error => errors.push(error.message));
  await page.waitForURL(url => url.protocol === "http:", { timeout: 120_000 });
  origin = new URL(page.url()).origin;
  await page.evaluate(() => localStorage.setItem("pi-locale", "en"));
  await page.reload();
  await page.getByRole("button", { name: "Settings", exact: true }).click();
  const settings = page.getByRole("dialog", { name: "Settings", exact: true });
  await settings.getByRole("button", { name: "General", exact: true }).click();
  const alerts = settings.getByRole("switch", { name: "AUTO / ACT human approval alerts", exact: true });
  await alerts.waitFor();
  await page.waitForFunction(() => document.querySelector('[role="switch"][aria-label="AUTO / ACT human approval alerts"]')?.getAttribute("aria-checked") === "true");
  const saved = page.waitForResponse(reply => reply.url().endsWith("/api/my-slim-pi/settings") && reply.request().method() === "PUT");
  await alerts.click();
  assert.equal((await saved).status(), 200);
  assert.deepEqual(JSON.parse(await readFile(permissionFile, "utf8")), { reviewer: { humanFallback: "pause", keep: true } });
  await settings.getByRole("button", { name: "Sub-agents", exact: true }).click();
  const active = settings.locator(".settings-section-host:not([hidden])");
  const chooseProfile = async name => { await active.locator(".config-sidebar-item").filter({ hasText: new RegExp(`^${name}$`) }).click(); };
  await chooseProfile("approver");
  assert.equal(await active.getByRole("textbox", { name: "System instructions", exact: true }).inputValue(), prompt.trim());
  await active.getByText("Configuration details", { exact: true }).click();
  await active.getByText(/allowedAgents: none/).waitFor();
  const chooseModel = async name => {
    const selector = active.getByRole("button", { name: "Model override", exact: true });
    await selector.click();
    await page.getByRole("listbox", { name: "Model override", exact: true }).getByRole("option", { name, exact: true }).click();
  };
  const saveProfile = async endpoint => {
    const response = page.waitForResponse(reply => reply.url().endsWith(endpoint) && reply.request().method() === "PUT");
    await active.getByRole("button", { name: "Save", exact: true }).click();
    assert.equal((await response).status(), 200);
  };
  await chooseModel("Review model");
  await active.getByRole("combobox", { name: "Thinking", exact: true }).selectOption("high");
  await saveProfile("/api/subagents/profiles");
  let stored = parseFrontmatter(await readFile(profileFile, "utf8"));
  assert.equal(stored.data.model, "fixture/reviewer");
  assert.equal(stored.data.thinking, "high");
  assert.equal(stored.data.allowedAgents, "none");
  assert.equal(stored.rest, prompt);
  assert.equal(stored.data.load_extensions, undefined);
  await chooseModel("Parent default");
  await saveProfile("/api/subagents/profiles");
  stored = parseFrontmatter(await readFile(profileFile, "utf8"));
  assert.equal(stored.data.model, undefined);
  await chooseProfile("Hermes");
  await chooseModel("Summary model");
  await saveProfile("/api/my-slim-pi/background-models");
  assert.deepEqual(JSON.parse(await readFile(hermesFile, "utf8")), { memoryMode: "policy-only", llmThinkingOverride: "off", llmModelOverride: "fixture/memory" });
  await chooseProfile("cli-builtin");
  assert.equal(await active.getByRole("textbox", { name: "System instructions", exact: true }).isDisabled(), true);
  assert.equal(await active.getByRole("button", { name: "Model override", exact: true }).isDisabled(), true);
  await active.getByRole("button", { name: "New sub-agent", exact: true }).click();
  await active.getByRole("textbox", { name: "Sub-agent ID", exact: true }).fill("ui-created");
  await active.getByRole("textbox", { name: "Description", exact: true }).fill("Created through the native editor");
  await active.getByRole("textbox", { name: "System instructions", exact: true }).fill("Native editor creation proof.");
  await chooseModel("Review model");
  await saveProfile("/api/subagents/profiles");
  const createdFile = join(agent, "agents/ui-created.md");
  assert.equal(parseFrontmatter(await readFile(createdFile, "utf8")).data.name, "ui-created");
  page.once("dialog", dialog => dialog.accept());
  const removed = page.waitForResponse(reply => reply.url().endsWith("/api/subagents/profiles") && reply.request().method() === "DELETE");
  await active.getByRole("button", { name: "Delete", exact: true }).click();
  assert.equal((await removed).status(), 200);
  await assert.rejects(access(createdFile));
  await page.evaluate(() => localStorage.setItem("pi-locale", "zh-CN"));
  await page.reload();
  await page.getByRole("button", { name: "设置", exact: true }).click();
  const chinese = page.getByRole("dialog", { name: "设置", exact: true });
  await chinese.getByRole("button", { name: "子代理", exact: true }).click();
  await chinese.locator(".config-sidebar-item").filter({ hasText: /^approver$/ }).click();
  await chinese.getByText("配置详情", { exact: true }).click();
  await page.screenshot({ path: join(area, "agents-zh.png") });
  await writeFile(join(area, "settings-zh.html"), `<!doctype html><html lang="zh-CN"><head><meta charset="utf-8"><style>html { font-family: "Microsoft YaHei", "Noto Sans SC", sans-serif; }</style></head><body>${await chinese.evaluate(element => element.outerHTML)}</body></html>`);
  await chinese.getByText("配置详情", { exact: true }).evaluate(element => { element.id = "agent-settings-font-probe"; });
  const cdp = await page.context().newCDPSession(page);
  await cdp.send("DOM.enable"); await cdp.send("CSS.enable");
  const { root } = await cdp.send("DOM.getDocument");
  const { nodeId } = await cdp.send("DOM.querySelector", { nodeId: root.nodeId, selector: "#agent-settings-font-probe" });
  const fontEvidence = await cdp.send("CSS.getPlatformFontsForNode", { nodeId });
  assert.ok(fontEvidence.fonts.some(font => /Microsoft YaHei|Noto Sans SC/.test(font.familyName)), "Chinese labels use a Simplified Chinese font");
  await cdp.detach();
  await chinese.locator(".config-sidebar-item").filter({ hasText: /^Hermes$/ }).click();
  await page.screenshot({ path: join(area, "hermes-zh.png") });
  await chinese.getByRole("button", { name: "常规", exact: true }).click();
  await chinese.getByRole("switch", { name: "AUTO / ACT 人工审批提醒", exact: true }).waitFor();
  await page.screenshot({ path: join(area, "general-zh.png") });
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(760, 520));
  await page.emulateMedia({ colorScheme: "dark" });
  await chinese.getByRole("button", { name: "子代理", exact: true }).click();
  await chinese.locator(".config-sidebar-item").filter({ hasText: /^Hermes$/ }).click();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth), true);
  await page.screenshot({ path: join(area, "hermes-narrow-dark.png") });
  assert.deepEqual(writes, [], "Settings must not dispatch a prompt or create a chat");
  assert.deepEqual(errors, []);
  const sessions = await page.evaluate(async () => (await (await fetch("/api/sessions")).json()));
  assert.ok(Array.isArray(sessions) ? sessions.length === 0 : sessions.sessions?.length === 0);
  console.log(JSON.stringify({ passed: true, nativeEditor: true, noSessionRequired: true, reviewerModel: true, reasoning: true, modelClear: true, hermesModel: true, profileCreateDelete: true, detailsInSettings: true, approvalInGeneral: true, noAgentPrompts: true, chineseFonts: fontEvidence.fonts.map(font => font.familyName), area }));
} catch (error) {
  for (const [index, page] of (await app.windows()).entries()) await page.screenshot({ path: join(area, `failure-${index}.png`) }).catch(() => {});
  throw error;
} finally {
  await app.evaluate(({ dialog }) => { dialog.showMessageBox = async () => ({ response: 0 }); }).catch(() => {});
  await app.close();
  if (origin) await assert.rejects(fetch(origin, { signal: AbortSignal.timeout(3000) }));
}
