import assert from "node:assert/strict";
import test from "node:test";
import {mkdtemp,mkdir,writeFile,readFile,rm} from "node:fs/promises";
import {tmpdir} from "node:os";
import {join} from "node:path";
import {createJiti} from "jiti";
const jiti=createJiti(import.meta.url,{tsconfigPaths:true});
const {readMySlimPiSettings,writeMySlimPiSettings}=await jiti.import("./my-slim-pi-settings.ts");
test("My Slim Pi settings preserve rules, reject unsupported installations and never default invalid values to approval",async t=>{
 const root=await mkdtemp(join(tmpdir(),"slim-settings-"));t.after(()=>rm(root,{recursive:true,force:true}));
 for(const dir of ["install","extensions/timrt-suite","extensions/pi-permission-suite"])await mkdir(join(root,dir),{recursive:true});
 await writeFile(join(root,"install/current-version"),"1.3.0");await writeFile(join(root,"extensions/timrt-suite/permissions.ts"),"fixture");
 const file=join(root,"extensions/pi-permission-suite/config.json"),bundle=join(root,"extensions/timrt-suite/timrt-fast.mjs");
 const config={path:{deny:{secret:"protected"}},reviewer:{humanFallback:"ask",other:"keep"}};
 await writeFile(file,JSON.stringify(config));
 assert.equal(readMySlimPiSettings(root).supported,false);
 await assert.rejects(writeMySlimPiSettings(false,root),/Update and rebuild/);
 await writeFile(bundle,'registerCommand("approval-fallback", fixture)');
 assert.equal((await writeMySlimPiSettings(false,root)).humanFallbackEnabled,false);
 const stored=JSON.parse(await readFile(file,"utf8"));assert.equal(stored.reviewer.humanFallback,"pause");
 assert.deepEqual(stored.path,config.path);assert.equal(stored.reviewer.other,"keep");
 assert.equal((await writeMySlimPiSettings(true,root)).humanFallbackEnabled,true);
 stored.reviewer.humanFallback="invalid";await writeFile(file,JSON.stringify(stored));assert.equal(readMySlimPiSettings(root).humanFallbackEnabled,false);
 await writeFile(file,"{");await assert.rejects(writeMySlimPiSettings(true,root));assert.equal(await readFile(file,"utf8"),"{");
});
